#!/usr/bin/env node
// Regenerates public/phone/icon-data.js from game-icons.net (CC BY 3.0) via the Iconify JSON package.
//   npm i --no-save @iconify-json/game-icons && node scripts/build-phone-icons.mjs
import { createRequire } from 'node:module';
import fs from 'node:fs';
const src = process.argv[2] || createRequire(import.meta.url).resolve('@iconify-json/game-icons/icons.json');
const j = JSON.parse(fs.readFileSync(src));
/** our glyph name -> game-icons name */
const MAP = {
  loyal: 'cross-shield', merlin: 'wizard-face', percival: 'visored-helm', minion: 'devil-mask', assassin: 'cloak-dagger',
  morgana: 'witch-face', mordred: 'crowned-skull', oberon: 'ghost',
  knight: 'crested-helmet', mage: 'wizard-staff', rogue: 'domino-mask', barbarian: 'battle-axe', rogueHooded: 'hood',
  crown: 'jewel-crown', leader: 'queen-crown', chalice: 'holy-grail', skull: 'death-skull', brokensword: 'shattered-sword', fire: 'campfire', hourglass: 'hourglass', tv: 'tv', scroll: 'scroll-unfurled',
  laurels: 'laurels', banner: 'knight-banner', daggers: 'daggers',
};
const out = {};
for (const [k, n] of Object.entries(MAP)) { if (!j.icons[n]) throw new Error(`missing ${n}`); out[k] = j.icons[n].body; }
fs.writeFileSync(new URL('../public/phone/icon-data.js', import.meta.url),
  `// GENERATED by scripts/build-phone-icons.mjs. Glyphs from game-icons.net (Lorc, Delapouite and contributors), CC BY 3.0.\n// 512x512 viewBox bodies.\nexport const GAME_ICONS = ${JSON.stringify(out, null, 1)};\n`);
console.log(`wrote ${Object.keys(out).length} glyphs`);
